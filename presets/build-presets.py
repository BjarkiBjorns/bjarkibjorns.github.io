#!/usr/bin/env python3
# Bundles every presets/*.json into presets/presets.js (LISSA_PRESETS).
# The app can't read JSON files directly on file:// or static hosting, so run
# this after adding, removing or renaming a preset file:
#
#   python3 presets/build-presets.py
#
# Chip names come from the filename: "-" and "_" become spaces, order is alphabetical.

import glob, json, os, re

here = os.path.dirname(os.path.abspath(__file__))
presets = []
for path in sorted(glob.glob(os.path.join(here, "*.json"))):
    base = os.path.splitext(os.path.basename(path))[0]
    name = re.sub(r"\s+", " ", re.sub(r"[-_]", " ", base)).strip()
    with open(path) as f:
        presets.append({"name": name, "state": json.load(f)})

with open(os.path.join(here, "presets.js"), "w") as f:
    f.write("// Generated by presets/build-presets.py from presets/*.json — don't edit by hand.\n")
    f.write("var LISSA_PRESETS = " + json.dumps(presets, indent=2) + ";\n")

print("presets.js: %d presets" % len(presets))
for p in presets:
    print("  " + p["name"])
